#!/usr/bin/env python3
"""--analyze on libraries it was never tuned on (benchmarks/heldout/apps), checked against two
measurements made without it:
  1. esbuild's metafile (`bytesInOutput`) for the same app: the same modules, and each module's
     share of its output within 2 points (the two outputs differ a little in size);
  2. our output's own source map, attributed byte by byte with Mozilla's `source-map` (what
     source-map-explorer does): each module's bytes as the map gives them, within 0.5% + 8 bytes.
     What the bundler wrote for a module (its CommonJS wrapper, its namespace object) has no source,
     and a map cannot say so inside a line, so a map gives it to the code before it: a module's
     share may be anything from its bytes without what was written for it to its bytes with it, and
     its neighbours' grow by as much. Comments (legal comments, the line naming the map) are no
     module's.
Also: the bytes attributed add up to the file, and the output is the same with and without it.
   usage: heldout-analyze.py [APP...]   (ESB=binary)"""
import json, os, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HERE = ROOT/'benchmarks/heldout'
OURS = str(Path(os.environ.get('ESB', ROOT/'out/bin/esb')).resolve())
ESBUILD = str(HERE/'node_modules/.bin/esbuild')
OUT = ROOT/'out/heldout/analyze'; OUT.mkdir(parents=True, exist_ok=True)
apps = sys.argv[1:] or sorted(p.stem for p in (HERE/'apps').glob('*.js') if p.stem != 'nodom')
RUNTIME = '<runtime>'

# Every generated byte to the source of the last mapping at or before it, anywhere in the file (a
# template literal's lines have no mappings of their own); a byte inside a comment (a legal comment,
# the line naming the map) to none. Comments are found by acorn.
BY_MAP = r'''
const { SourceMapConsumer } = require("source-map");
const acorn = require("acorn");
const fs = require("fs");
const [js, map] = process.argv.slice(1);
const code = fs.readFileSync(js, "utf8");
(async () => {
  const c = await new SourceMapConsumer(JSON.parse(fs.readFileSync(map, "utf8")));
  const comments = [];
  acorn.parse(code, { ecmaVersion: "latest", sourceType: "module", onComment: (block, text, start, end) => comments.push([start, end]) });
  const segs = []; c.eachMapping(m => segs.push(m), null, SourceMapConsumer.GENERATED_ORDER);
  const by = {}; let none = 0, si = 0, ci = 0, line = 1, col = 0, cur = null;
  for (let i = 0; i < code.length; i++) {
    while (si < segs.length && (segs[si].generatedLine < line || (segs[si].generatedLine === line && segs[si].generatedColumn <= col))) cur = segs[si++].source;
    while (ci < comments.length && comments[ci][1] <= i) ci++;
    const inComment = ci < comments.length && comments[ci][0] <= i;
    const b = Buffer.byteLength(code[i]);
    if (cur && !inComment) by[cur] = (by[cur] || 0) + b; else none += b;
    if (code[i] === "\n") { line++; col = 0; } else col++;  // columns count UTF-16 units, as indices do
  }
  console.log(JSON.stringify({ by, none }));
})();
'''


def name(p):
    p = str(p)
    i = p.find('node_modules/')
    return p[i:] if i >= 0 else p[p.find('apps/'):] if 'apps/' in p else p


def run(cmd):
    r = subprocess.run(cmd, cwd=HERE, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(f"{' '.join(cmd)}\n{r.stdout}{r.stderr[-2000:]}")
    return r.stdout


bad = []
for a in apps:
    o, plain = OUT/f'{a}.mjs', OUT/f'{a}.plain.mjs'
    run([OURS, f'apps/{a}.js', '--format=esm', '--minify', '--sourcemap', f'--outfile={o}', f'--analyze={OUT/a}'])
    run([OURS, f'apps/{a}.js', '--format=esm', '--minify', '--sourcemap', f'--outfile={plain}'])
    problems = []
    if o.read_bytes() != plain.read_bytes().replace(b'plain.mjs.map', b'mjs.map'):
        problems.append('the output changes with --analyze')
    an = json.loads((OUT/a/'analysis.json').read_text())
    out0 = an['outputs'][0]
    ours = {name(an['modules'][m['module']]['path']): m['bytes'] for m in out0['modules']}
    written = {name(an['modules'][m['module']]['path']): w['written'] for m in out0['modules']
               for w in an['modules'][m['module']]['outputs'] if w['output'] == 0}
    if sum(ours.values()) + out0['own'] != out0['bytes'] or out0['bytes'] != o.stat().st_size:
        problems.append(f"attributed {sum(ours.values())} + own {out0['own']} is not the file's {o.stat().st_size}")
    meta = OUT/f'{a}.meta.json'
    run([ESBUILD, f'apps/{a}.js', '--bundle', '--format=esm', '--minify', f'--outfile={OUT}/{a}.esbuild.mjs',
         f'--metafile={meta}', '--log-level=error'])
    eout = next(v for k, v in json.loads(meta.read_text())['outputs'].items() if k.endswith('.mjs'))
    theirs = {name(k): v['bytesInOutput'] for k, v in eout['inputs'].items() if v['bytesInOutput']}
    mine = {k: v for k, v in ours.items() if k != RUNTIME}
    if set(mine) != set(theirs):
        problems.append(f'modules only ours: {sorted(set(mine) - set(theirs))}, only esbuild: {sorted(set(theirs) - set(mine))}')
    t1, t2 = sum(mine.values()), sum(theirs.values())
    for k in set(mine) & set(theirs):
        if max(mine[k], theirs[k]) > 500 and abs(mine[k] / t1 - theirs[k] / t2) > 0.02:
            problems.append(f'{k}: {mine[k]} B ({100*mine[k]/t1:.1f}%) against esbuild {theirs[k]} B ({100*theirs[k]/t2:.1f}%)')
    sm = json.loads(subprocess.run(['node', '-e', BY_MAP, str(o), str(o) + '.map'], cwd=HERE,
                                   capture_output=True, text=True, check=True).stdout)
    mapped = {name(k): v for k, v in sm['by'].items()}
    # The written bytes the map may have moved: all of them, from any module to any other.
    slack = sum(written.values()) + ours.get(RUNTIME, 0)
    for k in set(mine) | set(mapped):
        x, y, w = mine.get(k, 0), mapped.get(k, 0), written.get(k, 0)
        tol = 8 + 0.005 * max(x, y)
        if y < x - w - tol or y > x + slack + tol:
            problems.append(f'{k}: {x} B ({w} written for it), the source map {y} B')
    moved = sum(abs(mine.get(k, 0) - mapped.get(k, 0)) for k in set(mine) | set(mapped))
    print(f"{a:10} {out0['bytes']:7} B, {len(mine)} modules, own {out0['own']}, runtime {ours.get(RUNTIME, 0)}, "
          f"unmapped {sm['none']}, |ours - map| {moved}: {'ok' if not problems else 'FAIL'}", flush=True)
    for p in problems:
        print('    ', p)
        bad.append(f'{a}: {p}')
sys.exit(1 if bad else 0)
